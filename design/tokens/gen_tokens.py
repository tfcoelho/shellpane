#!/usr/bin/env python3
"""Generate Swift design tokens from design/tokens/tokens.json.

The native-app equivalent of tokens.css + a Tailwind mapping: one source of
truth, so views say `Tokens.Colors.textMuted`, never a hex value. Each colour
is a dynamic NSColor that resolves light or dark from the view's appearance.

    python3 design/tokens/gen_tokens.py design/tokens/tokens.json Sources/ShellpaneUI/Tokens.swift

Standard library only. Run it again after every token change (including the
rebrand); the build does not regenerate it on its own.
"""

import json
import re
import sys


def camel(name):
    parts = re.split(r"[-_ ]+", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def rgb(hexv):
    h = hexv.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def ns(hexv):
    r, g, b = rgb(hexv)
    return "NSColor(srgbRed: %.4f, green: %.4f, blue: %.4f, alpha: 1)" % (r, g, b)


def dynamic(light, dark):
    return "dynamic(light: %s, dark: %s)" % (ns(light), ns(dark))


def public(d):
    return {k: v for k, v in d.items() if not k.startswith("_")}


def generate(tokens):
    col = tokens["color"]
    light, dark = public(col["light"]), public(col["dark"])
    if set(light) != set(dark):
        raise ValueError("light and dark colour roles differ: %s" % sorted(set(light) ^ set(dark)))
    conn_l, conn_d = public(col["connection"]["light"]), public(col["connection"]["dark"])
    if set(conn_l) != set(conn_d):
        raise ValueError("light and dark connection colours differ")

    out = [
        "// Generated by design/tokens/gen_tokens.py from design/tokens/tokens.json.",
        "// Do not edit by hand: change the JSON and run the generator again.",
        "",
        "import AppKit",
        "import SwiftUI",
        "",
        "public enum Tokens {",
        "    static func dynamic(light: NSColor, dark: NSColor) -> NSColor {",
        "        NSColor(name: nil) { appearance in",
        "            appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light",
        "        }",
        "    }",
        "",
        "    public enum NSColors {",
    ]
    for k in light:
        out.append("        public static let %s = %s" % (camel(k), dynamic(light[k], dark[k])))
    out += ["    }", "", "    public enum Colors {"]
    for k in light:
        out.append("        public static let %s = Color(nsColor: NSColors.%s)" % (camel(k), camel(k)))
    out += ["    }", ""]

    out.append("    public enum Space {")
    for v in tokens["space"]:  # named by value: Space.s8 is 8pt
        out.append("        public static let s%d: CGFloat = %s" % (v, v))
    out += ["    }", "", "    public enum Size {"]
    for k, v in public(tokens["size"]).items():
        out.append("        public static let %s: CGFloat = %s" % (camel(k), v))
    out += ["    }", "", "    public enum Radius {"]
    for k, v in public(tokens["radius"]).items():
        out.append("        public static let %s: CGFloat = %s" % (camel(k), v))
    out += ["    }", "", "    public enum Motion {"]
    for k, v in public(tokens["motion"]).items():
        m = re.match(r"^(\d+)ms$", str(v))
        if m:
            out.append("        public static let %s: Double = %s" % (camel(k), int(m.group(1)) / 1000.0))
    out += ["    }", "}", ""]

    out += [
        "/// Per-server colour tag. Stored by raw value in favorites.colour.",
        "public enum ConnectionColour: String, CaseIterable, Codable, Sendable {",
    ]
    for k in conn_l:
        out.append("    case %s" % camel(k))
    out += ["", "    public var nsColor: NSColor {", "        switch self {"]
    for k in conn_l:
        out.append("        case .%s: return Tokens.dynamic(light: %s, dark: %s)" % (camel(k), ns(conn_l[k]), ns(conn_d[k])))
    out += ["        }", "    }", "", "    public var color: Color { Color(nsColor: nsColor) }", "}", ""]
    return "\n".join(out)


def main(argv):
    if len(argv) != 3:
        print(__doc__.strip().split("\n\n")[1], file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as fh:
        tokens = json.load(fh)
    try:
        swift = generate(tokens)
    except (KeyError, ValueError) as exc:
        print("gen_tokens: %s" % exc, file=sys.stderr)
        return 1
    with open(argv[2], "w", encoding="utf-8") as fh:
        fh.write(swift)
    print("wrote %s" % argv[2])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
